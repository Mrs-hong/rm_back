#!/bin/bash
# ==========================================================================
# _colors.sh — 公共 ANSI 颜色码定义（被各脚本 source）
#
# 设计：
#   检测 stdout 是否为 TTY：非 TTY（如 plink 管道/重定向）时禁用颜色码，
#   避免 ANSI 转义序列污染输出（Windows 控制台非 PTY 不解析 \e[32m 等）
#
# 用法（在调用方脚本顶部）：
#   source "$(dirname "${BASH_SOURCE[0]}")/_colors.sh"
#
# 提供：G(绿) R(红) Y(黄) C(青) N(复位)
# ==========================================================================

if [ -t 1 ]; then
    G='\e[32m'; R='\e[31m'; Y='\e[33m'; C='\e[36m'; N='\e[0m'
else
    G=''; R=''; Y=''; C=''; N=''
fi
